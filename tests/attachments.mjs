import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createAttachments, attachmentPrompt, MAX_FILE} from '../server/lib/attachments.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jarvis-uploads-test-'));
const store = createAttachments(root);
try {
  for (const name of ['../x', '/tmp/x', 'a\\b', 'a\nb', '', 'a'.repeat(181)]) assert.throws(() => store.add(name, Buffer.from('data')), /Invalid attachment name/);
  assert.throws(() => store.add('empty', Buffer.alloc(0)), /10 MB/);
  assert.throws(() => store.add('huge', Buffer.alloc(MAX_FILE+1)), /10 MB/);
  const file = store.add('<script>.txt', Buffer.from('fixture data'));
  assert.equal(file.path, undefined);
  const [entry] = store.resolve([file.id]);
  assert.equal(fs.statSync(entry.path).mode & 0o777, 0o600);
  assert.equal(fs.statSync(path.dirname(entry.path)).mode & 0o777, 0o700);
  assert.equal(fs.readFileSync(entry.path, 'utf8'), 'fixture data');
  assert.throws(() => store.resolve(['../../etc/passwd']), /unavailable/);
  assert.throws(() => store.resolve([file.id,file.id]), /different files/);
  assert.throws(() => store.resolve(new Array(5).fill(file.id)), /four/);
  const script = store.add('evil.sh', Buffer.from('#!/bin/sh\necho never execute'));
  assert.equal(path.extname(store.resolve([script.id])[0].path), '.bin');
  const image = store.add('wrong.txt', Buffer.from([137,80,78,71,13,10,26,10]));
  assert.equal(image.type, 'image');
  assert.match(attachmentPrompt([entry]), /untrusted data/);
  entry.used = true;
  assert.throws(() => store.remove(file.id), /already part/);
  entry.at = Date.now() - 25*60*60*1000; entry.active = true;
  assert.equal(store.resolve([file.id]).length, 1);
  entry.active = false;
  assert.throws(() => store.resolve([file.id]), /unavailable/);
  const big = Buffer.alloc(MAX_FILE);
  store.clear();
  for (let i=0;i<10;i++) store.add('size.txt', big);
  assert.throws(() => store.add('over.txt',Buffer.from('x')), /storage is full/);
  store.clear();
  assert.throws(() => store.resolve([image.id]), /unavailable/);
  console.log('PASS: private uploads, traversal/size/count/quota rejection, image signatures, retention, active-turn protection and cleanup.');
} finally { store.close(); fs.rmSync(root,{recursive:true,force:true}); }
